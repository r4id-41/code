// dibawah ini adalah cara menampilkan output di C++

#include <iostream> // iostream adalah library yang digunakan dalam input dan output di C++
using namespace std; // menggunakan namespace std, agar tidak perlu menuliskan std::cout atau std::cin

int main() {
    cout << "Hello, World!" << endl; // cout adalah fungsi yang digunakan untuk menampilkan output
    cout << "Hallo namaku Kovix" << endl; // endl adalah fungsi yang digunakan untuk membuat baris baru
    cout << "umuurku 17 tahun" << endl;
    return 0; // mengembalikan nilai 0 atau false dan menandakan bahwa program telah berakhir
}