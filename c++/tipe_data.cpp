#include <iostream>
using namespace std;

int main() {
    // tipe data integer
    // integer adalah tipe data yang digunakan untuk menyimpan bilangan bulat
    int umur = 17;
    cout << "Umurku " << umur << " tahun" << endl;

    // tipe data float
    // float adalah tipe data yang digunakan untuk menyimpan bilangan desimal
    float berat_badan = 50.5;
    cout << "Berat badanku " << berat_badan << " kg" << endl;

    // tipe data double
    // double adalah tipe data yang digunakan untuk menyimpan bilangan desimal dengan presisi yang lebih tinggi
    double tinggi_badan = 170.5;
    cout << "Tinggi badanku " << tinggi_badan << " cm" << endl;

    // tipe data char
    // char adalah tipe data yang digunakan untuk menyimpan karakter
    // contoh: 'a', 'b', 'c', '1', '2', '3', '!', '@', '#', dll
    // char hanya bisa menyimpan satu karakter saja
    char jenis_kelamin = 'L';
    cout << "Jenis kelaminku " << jenis_kelamin << endl;

    // tipe data string
    // string adalah tipe data yang digunakan untuk menyimpan teks
    // string adalah kumpulan dari karakter, seperti "Kovix", "Hello, World!", "17", "50.5", dll
    // string bisa menyimpan lebih dari satu karakter dan diapit oleh tanda kutip dua ("")
    string nama = "Kovix";
    cout << "Namaku " << nama << endl;

    return 0;
}