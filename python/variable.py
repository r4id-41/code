# Variable bisa memudahkan kita dalam menyimpan data, karena kita bisa memanggil data tersebut 
# dengan memanggil variable tersebut.
# Dengan variable kita bisa menggabungkan data, misalnya kita ingin menggabungkan 
# nama, umur, dan alamat kita dalam satu kalimat.
# Contoh:

nama = "Nico"
umur = "16"
alamat = "Purwosari"
# Kita bisa menggabungkan data diatas dengan cara:
Biodata = "Nama saya " + nama + ", umur saya " + umur + " tahun, dan alamat saya di " + alamat
print(Biodata) # ini akan menampilkan Nama saya Nico, umur saya 16 tahun, dan alamat saya di Purwosari

