# Di python ada yang namanya variable, variable ini digunakan untuk menyimpan nilai data.
# Contoh:

a = "Aku sedang belajar Python" # a sebagai variable yang menyimpan nilai data yang berbunyi Aku sedang belajar Python

print(a) # ini akan memanggil variable a untuk ditampilkan

# ciri-ciri variable:
