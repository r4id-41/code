# Di python ada beberapa operasi aritmatika yang bisa digunakan, yaitu:
# 1. Penjumlahan (+)
# 2. Pengurangan (-)
# 3. Perkalian (*)
# 4. Pembagian (/)
# 5. Modulus (%)
# 6. Pangkat (**)
# 7. Pembagian Bulat (//)

# Penjumlahan (+)
# Penjumlahan digunakan untuk menjumlahkan dua bilangan atau lebih.
# Contoh:

a = 10
b = 20
c = a + b
print(c) # ini akan menampilkan hasil penjumlahan dari a dan b

# Pengurangan (-)
# Pengurangan digunakan untuk mengurangkan dua bilangan atau lebih.
# Contoh:

d = 10
e = 20
f = e - d
print(f) # ini akan menampilkan hasil pengurangan dari e dan d

# Perkalian (*)
# Perkalian digunakan untuk mengalikan dua bilangan atau lebih.
# Contoh:

g = 10
h = 20
i = g * h
print(i) # ini akan menampilkan hasil perkalian dari g dan h

# Pembagian (/)
# Pembagian digunakan untuk membagi dua bilangan atau lebih.
# Contoh:

j = 10
k = 20
l = k / j
print(l) # ini akan menampilkan hasil pembagian dari k dan j

# Modulus (%)
# Modulus digunakan untuk mendapatkan sisa pembagian dari dua bilangan.
# Contoh:

m = 10
n = 20
o = n % m
print(o) # ini akan menampilkan sisa pembagian dari n dan m

# Pangkat (**)
# Pangkat digunakan untuk menghitung hasil pangkat dari dua bilangan.
# Contoh:

p = 10
q = 2
r = p ** q
print(r) # ini akan menampilkan hasil pangkat dari p dan q

# Pembagian Bulat (//)
# Pembagian bulat digunakan untuk membagi dua bilangan dan mendapatkan hasil pembagian bulat.
# Hasil pembagian ini adalah bilangan bulat yang terdekat dari hasil pembagian sebenarnya.
# Contoh:

s = 10
t = 3
u = s // t
print(u) # ini akan menampilkan hasil pembagian bulat dari s dan t