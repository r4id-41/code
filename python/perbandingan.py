# Di python ada beberapa perbandingan yang bisa digunakan, yaitu:
# 1. Sama dengan (==)
# 2. Tidak sama dengan (!=)
# 3. Lebih besar dari (>)
# 4. Lebih kecil dari (<)
# 5. Lebih besar sama dengan (>=)
# 6. Lebih kecil sama dengan (<=)

# Sama dengan (==)
# Sama dengan digunakan untuk membandingkan apakah dua nilai sama atau tidak.
# Contoh:

a = 10
b = 10
c = a == b
print(c) # ini akan menampilkan True karena a sama dengan b

# Tidak sama dengan (!=)
# Tidak sama dengan digunakan untuk membandingkan apakah dua nilai tidak sama.
# Contoh:

d = 10
e = 20
f = d != e
print(f) # ini akan menampilkan True karena d tidak sama dengan e

# Lebih besar dari (>)
# Lebih besar dari digunakan untuk membandingkan apakah nilai pertama lebih besar dari nilai kedua.
# Contoh:

g = 10
h = 20
i = h > g
print(i) # ini akan menampilkan True karena h lebih besar dari g

# Lebih kecil dari (<)
# Lebih kecil dari digunakan untuk membandingkan apakah nilai pertama lebih kecil dari nilai kedua.
# Contoh:

j = 10
k = 20
l = j < k
print(l) # ini akan menampilkan True karena j lebih kecil dari k

# Lebih besar sama dengan (>=)
# Lebih besar sama dengan digunakan untuk membandingkan apakah nilai pertama lebih besar atau sama dengan 
# nilai kedua.
# Contoh:

m = 10
n = 20
o = n >= m
print(o) # ini akan menampilkan True karena n lebih besar dari m

# Lebih kecil sama dengan (<=)
# Lebih kecil sama dengan digunakan untuk membandingkan apakah nilai pertama lebih kecil atau sama dengan 
# nilai kedua.
# Contoh:

p = 10
q = 20
r = p <= q
print(r) # ini akan menampilkan True karena p lebih kecil dari q
